-- REV.CC 기준(baseline) 스키마. Flyway 도입 직전 운영 DB(Neon)의 스키마를 그대로 옮긴 것이다.
-- 이전에는 Hibernate ddl-auto:update, backend/migrations/*.sql(수동), board-service schema.sql(매 부팅),
-- VehicleRepository(@PostConstruct)가 각자 테이블을 만들었다. 이제 스키마는 Flyway만 변경한다.
--
-- 이미 테이블이 있는 DB는 baseline-on-migrate로 이 파일을 실행하지 않고 "적용됨"으로만 기록한다.
-- 따라서 이 파일은 수정하지 않는다. 스키마 변경은 항상 새 버전(V2, V3, ...) 파일로 추가한다.

-- 회원. 인증과 로그인 이름은 여기에만 둔다(unique 제약 이름은 Hibernate가 생성했던 이름 그대로).
CREATE TABLE users (
